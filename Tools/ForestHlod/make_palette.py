"""Bake three asymmetrical photo-derived crown variants per species into the C# palette.
No runtime texture import or extra material is needed; each crown is stamped only once.
"""
from pathlib import Path
import base64, json, math
import numpy as np
from PIL import Image, ImageDraw
root=Path(__file__).resolve().parents[2]
out=root/'Tools/ForestHlod/Review'
species=['oak','birch','spruce','pine']
tints=[(.80,.86,.64),(.82,.85,.63),(.74,.84,.69),(.82,.86,.72)]
models=json.loads((out/'models.json').read_text())
model_names=['Scenery_Tree','Scenery_Birch','Scenery_Spruce','Scenery_Pine']
def linear(c): return np.where(c<=.04045,c/12.92,((c+.055)/1.055)**2.4)
def srgb(c): return np.where(c<=.0031308,c*12.92,1.055*np.maximum(c,0)**(1/2.4)-.055)
means=[];radii=[];raw=[]
canvas=Image.new('RGB',(768,1080),(24,29,26));draw=ImageDraw.Draw(canvas)
for s,t in zip(species,tints):
    image=Image.open(root/f'Assets/DroneSandbox/Textures/PBR/impostor_{s}.png').convert('RGBA').crop((512,0,1024,512))
    a=np.asarray(image,dtype=float)/255;mask=a[:,:,3]>.45;c=linear(a[:,:,:3])*linear(np.array(t))
    mean=c[mask].mean(axis=0);means.append(srgb(mean))
    box=models[model_names[len(radii)]][2];width=box['hi'][0]-box['lo'][0];height=box['hi'][1]-box['lo'][1]
    radii.append(math.sqrt(float(mask.mean())/math.pi)*width/height)
    ys,xs=np.nonzero(mask);image=image.crop((int(xs.min()),int(ys.min()),int(xs.max()+1),int(ys.max()+1)))
    for variant in range(3):
        # Separate asymmetric views of the existing crown photograph, rather than one repeating quilt.
        pic=image.rotate(variant*117,resample=Image.Resampling.BICUBIC,expand=False)
        w,h=pic.size
        if variant:pic=pic.crop((int(w*.04*variant),0,w,int(h*(1-.035*variant))))
        pic=pic.resize((16,16),Image.Resampling.LANCZOS)
        a=np.asarray(pic,dtype=float)/255
        lum=linear(a[:,:,:3])@np.array([.2126,.7152,.0722]);alpha=np.clip((a[:,:,3]-.15)/.7,0,1)
        lum/=max(.001,(lum*alpha).sum()/max(1,alpha.sum()))
        atlas=np.stack((np.clip(lum,.35,1.8)*128,alpha*255),axis=-1).round().astype('uint8')
        raw.append(atlas.tobytes())
        preview=srgb(np.clip(mean*lum[:,:,None]*alpha[:,:,None]+linear(np.array([54,70,42])/255)*(1-alpha[:,:,None]),0,1))
        canvas.paste(Image.fromarray((preview*255).astype('uint8')).resize((256,256)),(variant*256,len(means)*270-250))
    draw.text((8,(len(means)-1)*270+3),s+' / three photo-derived variants',fill='white')
canvas.save(out/'crown-atlas.png')
p=root/'Assets/DroneSandbox/Scripts/ForestPalette.cs'
source='''using UnityEngine;

namespace DroneSandbox
{
    // Measured top-view photo colours and three crown variants per species, generated by make_palette.py.
    public static class ForestPalette
    {
        public static readonly Color32[] Colours =
        {
COLOURS
        };
        public static readonly float[] RadiusPerHeight = { RADII };
        public static readonly Color Ground = new Color(54f / 255f, 70f / 255f, 42f / 255f).linear;
        static readonly byte[] Pictures = System.Convert.FromBase64String(
BASE64);

        // Match the tinted photo cards in linear light, including their shadowed ground footprint.
        public static Color Crown(ForestPattern.Stand stand) =>
            ((Color)Colours[stand.species]).linear * Mathf.Pow(ForestPattern.Tint(stand.shade), 2.2f);

        // Density after Poisson rejection and clustering is measured by the production-source harness.
        public static Color Linear(ForestPattern.Stand stand)
        {
            float coverage = 1f - Mathf.Exp(-Mathf.PI * stand.radius * stand.radius * 0.0057f);
            return Color.Lerp(Ground, Crown(stand), coverage) * 1.10f;
        }

        // Bilinear filtering prevents nearest-texel speckle when a small crown crosses a baked pixel.
        public static float Picture(int species, int variant, float u, float v, out float alpha)
        {
            if (u < 0f || v < 0f || u > 1f || v > 1f) { alpha = 0f; return 1f; }
            float x = u * 15f, z = v * 15f;
            int i = Mathf.Min(14, (int)x), j = Mathf.Min(14, (int)z), k = ((species * 3 + variant) * 256 + j * 16 + i) * 2;
            float fx = x - i, fz = z - j;
            alpha = Mathf.Lerp(Mathf.Lerp(Pictures[k + 1], Pictures[k + 3], fx), Mathf.Lerp(Pictures[k + 33], Pictures[k + 35], fx), fz) / 255f;
            return Mathf.Lerp(Mathf.Lerp(Pictures[k], Pictures[k + 2], fx), Mathf.Lerp(Pictures[k + 32], Pictures[k + 34], fx), fz) / 128f;
        }
    }
}
'''
encoded=base64.b64encode(b''.join(raw)).decode()
source=source.replace('COLOURS','\n'.join('            new Color32('+', '.join(str(round(v*255)) for v in mean)+', 255),' for mean in means))
source=source.replace('RADII',', '.join(f'{v:.8f}f' for v in radii))
source=source.replace('BASE64',' +\n'.join('            "'+encoded[i:i+128]+'"' for i in range(0,len(encoded),128)))
p.write_bytes(source.replace('\n','\r\n').encode())
(out/'palette.json').write_text(json.dumps(dict(species=species,tints=tints,srgb_means=[m.tolist() for m in means],radius_per_height=radii,variants_per_species=3,atlas_bytes=len(b''.join(raw))),indent=2))
print('Generated 12 crown pictures and measured colours/radii')
